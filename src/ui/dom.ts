/**
 * Minimal DOM construction helpers. Text always goes through text nodes, never
 * through innerHTML, because run tags, topic ids and file names are untrusted input.
 */

export type Child = Node | string | number | null | undefined | false | readonly Child[];

type Handler = (event: Event) => void;
export type Attrs = Record<string, string | number | boolean | null | undefined | Handler>;

function append(parent: Node, child: Child): void {
  if (child === null || child === undefined || child === false) return;
  if (Array.isArray(child)) {
    for (const c of child as readonly Child[]) append(parent, c);
  } else if (child instanceof Node) {
    parent.appendChild(child);
  } else {
    parent.appendChild(document.createTextNode(String(child)));
  }
}

function setAttrs(el: Element, attrs: Attrs | null | undefined): void {
  if (!attrs) return;
  for (const [key, value] of Object.entries(attrs)) {
    if (value === null || value === undefined || value === false) continue;
    if (typeof value === 'function') {
      el.addEventListener(key.startsWith('on') ? key.slice(2).toLowerCase() : key, value);
    } else {
      el.setAttribute(key, value === true ? '' : String(value));
    }
  }
}

export function h<K extends keyof HTMLElementTagNameMap>(tag: K, attrs?: Attrs | null, ...children: Child[]): HTMLElementTagNameMap[K] {
  const el = document.createElement(tag);
  setAttrs(el, attrs);
  for (const child of children) append(el, child);
  return el;
}

const SVG_NS = 'http://www.w3.org/2000/svg';

export function s<K extends keyof SVGElementTagNameMap>(tag: K, attrs?: Attrs | null, ...children: Child[]): SVGElementTagNameMap[K] {
  const el = document.createElementNS(SVG_NS, tag);
  setAttrs(el, attrs);
  for (const child of children) append(el, child);
  return el;
}

export function replaceChildren(parent: Element, ...children: Child[]): void {
  parent.replaceChildren();
  for (const child of children) append(parent, child);
}

